    public void limparCampos(){
        cSenha.setText("");
    }
    
    public void verificar(){
        if (cbUsuario.getSelectedItem().equals("recepcionista") && cSenha.getText().equals("123")){
            entrar();
            limparCampos();
            
        } else if (cbUsuario.getSelectedItem().equals("administrador") && cSenha.getText().equals("admin")){
            entrar();
            limparCampos();
            
        }
    }
    
    public void entrar(){
        TelaPrincipal Principal = new TelaPrincipal();
        
        func.setUsuario(cbUsuario.getSelectedItem().toString());
        func.setSenha(cSenha.getText());
        
        dispose();
        
        Principal.setVisible(true);
        Principal.setLocationRelativeTo(null);
    }
    
    public void MostrarSenha(){
        if(bMostrarSenha.isSelected()){
            cSenha.setEchoChar((char)0);
        } else {
            cSenha.setEchoChar('*');
        }
    }
    
