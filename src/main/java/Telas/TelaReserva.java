    public void montaTabela(){
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("ID");
        modelo.addColumn("NOMES");
        modelo.addColumn("QUARTO");
        modelo.addColumn("CHECK IN");
        modelo.addColumn("CHECK OUT");
        modelo.addColumn("NOITE");
        modelo.addColumn("TOTAL");
        modelo.addColumn("STATUS");
        modelo.addColumn("AÇÃO");
        for (Hospede h : Global.ListaHospede) {
            modelo.addRow(new Object[]{h.getNome(), h.getQuartos(), h.getCheckin(), h.getCheckout(), h.getDias(), h.getValor()});
        }
        tabela.setModel(modelo);
    }
