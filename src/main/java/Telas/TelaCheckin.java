    public void Salvar(){
        cliente.setNome(cNome.getText());
        cliente.setEmail(cEmail.getText());
        cliente.setCpf(cCpf.getText());
        cliente.setTelefone(cTelefone.getText());
        
        cliente.setCheckin(Integer.valueOf(cCheckin.getText()));
        cliente.setCheckout(Integer.valueOf(cCheckout.getText()));
        cliente.setAdultos(Integer.valueOf(cAdultos.getText()));
        cliente.setCriancas(Integer.valueOf(cCriancas.getText()));
        
        soma();
        
        Global.ListaHotel.add(hotel);
        Global.ListaHospede.add(cliente);
        
        System.out.println(cliente);
        System.out.println(hotel);
    }
    
    public void soma(){
        cliente.setDias(cliente.getCheckout() - cliente.getCheckin());
        
        cliente.setValor(Double.valueOf(cliente.getAdultos() * valores.getAdulto()) + (cliente.getCriancas() * valores.getCriança() +
                cliente.getQuartos() * cliente.getDias()));
    }
    
